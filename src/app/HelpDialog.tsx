          <p>文字▼の「指摘」（N）は、クリックで文書全体の通し番号の印を置き、内容を入力します。Ctrl+Enter または欄の外のクリックで確定します。Esc も内容を確定して印を残し、「選択」に戻ります。印のダブルクリックで内容を直せます。</p>
