import { useEffect, useRef } from 'react'

interface Props {
  open: boolean
  onClose(): void
}

export function HelpDialog({ open, onClose }: Props) {
  const dialogRef = useRef<HTMLDialogElement>(null)

  useEffect(() => {
    const dialog = dialogRef.current
    if (!dialog) return
    if (open && !dialog.open) dialog.showModal()
    if (!open && dialog.open) dialog.close()
  }, [open])

  return (
    <dialog ref={dialogRef} className="help-dialog" aria-labelledby="help-title" onCancel={onClose} onClose={onClose}>
      <div className="help-dialog-header">
        <h1 id="help-title">かるPDFの使い方</h1>
        <button type="button" aria-label="使い方を閉じる" onClick={onClose}>×</button>
      </div>
      <div className="help-dialog-body">
        <section>
          <h2>開く・保存・確定保存・印刷</h2>
          <ul>
            <li>「開く」または <kbd>Ctrl</kbd>+<kbd>O</kbd> でPDFを開きます。複数のPDFはタブで切り替えます。</li>
            <li>「上書き保存」は元のファイルへ保存します。ブラウザから書き込みの許可を求められることがあります。</li>
            <li>「別名で保存」は編集できる書き込みを残したPDFを新しい名前で保存します。</li>
            <li>「ヘルプ → 履歴の設定」でファイル履歴を削除し、記憶を停止できます。ブラウザのファイルアクセス許可はブラウザの設定で取り消します。</li>
            <li>「確定して別名で保存」は書き込みをページへ焼き付けます。確定版の書き込みは後から編集できません。</li>
            <li>「印刷」または <kbd>Ctrl</kbd>+<kbd>P</kbd> でPDFを新しいタブに開き、そのタブの印刷ボタンから印刷します。</li>
          </ul>
        </section>
        <section>
          <h2>書き込みの道具とキー</h2>
          <p>選択（V）、文字（T）、吹き出し（C）、線（L）、矢印（A）、四角（R）、丸（O）、記号（S）、蛍光ペン（H）、手書き（P）を使えます。右の「書式」で色・太さ・文字サイズ・書体を変えます。</p>
          <p>すべての道具は「選択」を押すか <kbd>Esc</kbd> を押すまで続けて使えます。作った書き込みは選ばれ、書式の変更や Delete での削除ができます。移動や大きさの変更は「選択」に切り替えて行います。</p>
          <p>記号は12種類と大きさを選べ、続けて置けます。やめるときは <kbd>Esc</kbd> か「選択」です。文字や吹き出しの入力中は、書式の「記号を挿入」からカーソル位置に記号を入れられます。</p>
          <p>文字・吹き出し・指摘の入力中は、書式の「定型文」から文を挿入できます。登録内容は、記憶をオンにした場合だけこのPCに保存します。</p>
          <p>検索やページ一覧などで移動した後は、「表示」の前・次の表示で戻れます。図面上にフォーカスがあるときは Alt+← / Alt+→ も使えます。「ページ → 用紙サイズ一覧」はPDF内の各ページ寸法を表示します。</p>
          <p>書き込み一覧では指摘を未回答・回答済・修正済・確認済で管理し、「詳細」に分野、回答、修正確認、図面番号を入力できます。旧版の対応済は区別して残します。一覧は100件ずつ表示します。</p>
          <p>「計測 → 個数カウント」で、書式の「種類」を決めて図面をクリックします。書き込み一覧を個数カウントで絞ると種類・ページ別の集計とCSVを出せます。誤クリックは元に戻すか、選択して削除します。</p>
          <p>「文字 → 変更記録」で変更箇所と内容を記録します。一覧の詳細に変更理由と関連指摘を指定でき、変更一覧のCSVも出せます。</p>
          <p>比較は任意の2つのPDFに使えます。建築・電気・機械の図面にも「透過で重ねる」が使え、左右表示は移動と拡大を同期します。「位置合わせ・ページ対応・指摘引継ぎ」を開き、2点で位置合わせを選ぶと、旧版1点目→新版の同じ1点目→旧版2点目→新版の同じ2点目で補正します。ページ対応はJSONに保存して再読込できます。</p>
          <p>比較中の図面で「この図面の指摘を引き継ぐ」を選び、内容と候補位置を確認したものだけ新版へ追加します。旧版は残り、引継ぎの再実行では重複を除きます。修正されたかは利用者が確認してください。</p>
          <p>文字を選択した後の「文字を修正…」は横書き1行全体の限定編集です。修正したコピーを別タブで開き、原文のタブを残します。対応できない構造は原文を残す訂正注釈に切り替えられます。</p>
          <p>縮尺の「よく使う縮尺」は、詳細図用の1/5・1/10・1/20・1/25・1/30、平面図用の1/50・1/100・1/200などを選べます。任意の分母入力と、図面の寸法をなぞる校正も使えます。縮小されたPDFは原図の用紙も合わせて指定してください。</p>
          <p>四角と丸は塗り・枠線・透明度を選べます。四角の「白塗りにする」は上に白い四角を重ねる機能で、下の文字やデータはファイルに残ります。</p>
          <p>文字と吹き出しには背景色と枠線を付けられ、文字と背景・枠の透明度を別々に選べます。吹き出しは指摘する点から文字枠までドラッグしてください。</p>
          <p>蛍光ペンと手書きは、<kbd>Shift</kbd>を押しながら描くと5°刻みの直線になります。<kbd>Ctrl</kbd>では好きな角度の直線、<kbd>Ctrl</kbd>+<kbd>Shift</kbd>では Shift と同じ直線になります。</p>
          <p>線・矢印・計測線も Shift で5°刻みになります。矢印と吹き出しの「矢印先端の大きさ」は線幅とは別に指定でき、既存の書き込みを選んで変更することもできます。</p>
          <p>選択中に <kbd>Shift</kbd> を押しながらクリックすると、複数の書き込みを選べます。何もない所から囲むようにドラッグしてもまとめて選べます。<kbd>Ctrl</kbd>+<kbd>C</kbd>／<kbd>X</kbd>／<kbd>V</kbd> でコピー・切り取り・貼り付け、<kbd>Ctrl</kbd>+<kbd>D</kbd> で複製します。</p>
          <p>「文字に印」（M）では、「文字を選択」で PDF の文字を選んでコピーし、「文字ハイライト」「文字に下線」「文字に取り消し線」で選んだ文字だけに印を付けられます。</p>
          <p>書き込みを選んで方向キーを押すと1pt、<kbd>Shift</kbd>+方向キーでは10ptずつ動かせます。文字への印は文字に結び付いているため動かせません。</p>
          <p><kbd>Esc</kbd> を1回押すと、入力を確定して閉じ、描きかけは消して「選択」に戻ります。書き込みや文字の選択、検索の強調も消え、入力欄のフォーカスは外れます。メニューやダイアログが開いているときはそれだけを閉じ、縮尺をなぞる途中では縮尺の画面に戻ります。ページ整理では整理をやめます。<kbd>Ctrl</kbd>+<kbd>Z</kbd> で元に戻し、<kbd>Ctrl</kbd>+<kbd>Y</kbd> でやり直します。</p>
        </section>
        <section>
          <h2>雲マークと指摘</h2>
          <p>図形▼の「雲（四角）」はドラッグで囲みます。「雲（多角形）」はクリックで点を足し、ダブルクリックか Enter で閉じます。Backspace で最後の点を消し、Esc で中止、Shift で5度刻みに揃えます。書式で色・太さ・塗り・透明度・雲の大きさを選べます。</p>
          <p>文字▼の「指摘」（N）は、クリックで文書全体の通し番号の印を置き、内容を入力します。Ctrl+Enter または欄の外のクリックで確定します。Esc も内容を確定して印を残し、「選択」に戻ります。印のダブルクリックで内容を直せます。</p>
          <p>指摘は書式で色・大きさ・状態を変えます。対応済は灰色とチェックになります。左の「書き込み」を「指摘」で絞り込むと番号順に表示され、状態を変更できます。「指摘一覧を CSV に書き出す」で Excel 用の一覧を作れます。「番号を振り直す」はページ・上・左の順に番号を付け直し、Ctrl+Z で戻せます。削除では欠番を残し、コピーには新しい番号を付けます。</p>
        </section>
        <section>
          <h2>ページ整理</h2>
          <p>ページの並べ替え、回転、削除、白紙の挿入、抽出、分割、ほかのPDFの追加ができます。「適用」を押すまで元の並びは変わりません。</p>
          <p>通常・拡大プレビューは25％・50％・75％にも縮小できます。100％はプレビュー領域に合わせた大きさです。</p>
          <p>ほかのPDFから追加したページでは、しおり・リンク・フォームは移りません。</p>
        </section>
        <section>
          <h2>左右に並べて表示</h2>
          <p>表示▼ →「左右に並べて表示」または Ctrl+\ で切り替えます。左は編集用、右は閲覧専用です。右の見出しで文書・ページ・倍率を選び、境目をドラッグして幅を変えられます。</p>
          <p>「ページを合わせて動かす」をオンにすると、動かした側のページ内の位置と、幅に対する倍率にもう片方が合わせます。同じ文書を出す場合は最初はオフです。「⇄ 入れ替え」で右の文書を左に移して編集できます。右には保存済みの書き込みだけが見え、保存・元に戻す・道具のキーは左の文書に働きます。</p>
          <p>右にフォーカスがあるときの方向キーと PageUp・PageDown は右をスクロールします。ページ整理中は一時的に1つの表示に戻り、閉じると並べた表示に戻ります。</p>
        </section>
        <section>
          <h2>2つの PDF を比較</h2>
          <p>表示▼ →「2つの PDF を比較…」で旧版・新版を選びます。重ねる表示は旧版だけの線が赤、新版だけが青、共通が灰色です。並べる表示では左右の位置と倍率が同期します。比較中は閲覧専用です。</p>
          <p>旧・新のページ番号を変えて対応を合わせます。違いの一覧、‹・›、N・P キーで変わった場所へ拡大します。方向キーで新版を画面の1px分、Shiftと一緒なら10px分動かし、「戻す」で位置合わせを解除します。ずれはページの組ごとに覚えます。</p>
          <p>既定では書き込みを除き、「書き込みも比べる」で保存済みの書き込みを含めます。未保存の書き込みは先に保存してください。「終わる」で元の画面に戻ります。</p>
        </section>
        <section>
          <h2>画像から PDF を作る</h2>
          <p>ファイル▼ →「画像から PDF を作る…」でJPEG・PNGを複数選びます。画面へ画像をドロップしても開けます。並び・用紙・向き・余白・1ページの枚数・画質を選び、［作成］を押してください。新しい未保存のタブに開き、Ctrl+Sで保存できます。</p>
          <p>ページ整理の 挿入▼ →「画像を挿入…」では、選んだページの後（選ばなければ末尾）へ下書きとして追加します。［適用］で反映します。標準は長辺2400px、小さくは1600pxに縮め、元のままではJPEGを再圧縮しません。HEICはJPEGに変換してから選んでください。</p>
        </section>
        <section>
          <h2>ページ番号・ヘッダー・フッター</h2>
          <p>ページ▼の「ページ番号・ヘッダー・フッター…」で、上下6か所にページ番号、総ページ数、日付、ファイル名を入れられます。内容として書き込むため提出用の書類にも使え、かるPDFで付けたものは後から付け直し・削除できます。</p>
          <p>ページを並べ替えた後に番号を振り直すときは、同じ画面で［適用］を押してください。</p>
        </section>
        <section>
          <h2>アプリとして使う</h2>
          <p>EdgeまたはChromeのメニューから「アプリをインストール」を選びます。インストール後は、エクスプローラーのPDFの「プログラムから開く」で「かるPDF」を選べます。</p>
          <p>対応ブラウザは最新版のEdgeとChromeです。初回表示後はオフラインでも使えます。</p>
        </section>
        <section>
          <h2>データの扱い</h2>
          <p>PDFはパソコンの外へ送信しません。自動保存はしないため、必要なときに保存してください。</p>
        </section>
      </div>
      <div className="help-dialog-actions"><button type="button" onClick={onClose}>閉じる</button></div>
    </dialog>
  )
}
