// - 公共建築工事標準単価積算基準（令和8年改定）で施工の区分が書かれている品目は、その区分を候補にする。
//   単価の補正（倍率）は利用者が別途行うので、候補には書かない。
// - 基準で区分していない品目（盤類・機器・天井や壁の器具・屋外機器など）にも、設置方法の候補を付ける。
// - 照明器具は、今の候補（天井直付・天井埋込・壁付・吊下げ・床置・据置）に基準の区分を足して両方残す。
// - ケーブルラックは、今の候補（屋内・屋外）に基準の区分（1段積・2段積の2段目）を足して両方残す。
//
// 規則は上から順に見て、最初に当たった規則の候補を使う。品目がもともと持つ候補（既存の標準マスタの
// 電線・ケーブル・電線管など、摘要の施工・処理の区分）の後ろに、重複なく足す。

export interface ConditionRule {
  /** 品目の種類（catalog の CatalogItem.type。既存マスタは略号の種類、内訳書の品目は名称） */
  types?: readonly string[]
  /** 品目の分類（CatalogItem.category） */
  categories?: readonly string[]
  conditions: readonly string[]
  /** 'standard' = 標準単価積算基準の区分、'mounting' = 設置方法（実務の候補） */
  basis: 'standard' | 'mounting'
}

